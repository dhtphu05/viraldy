const analysisFor = (
    assetId: string,
    score: number,
    summary: string,
    reason: string,
    nextAction: string,
    dims: Array<
        [UgcAnalysis["dimensions"][number]["id"], number, string, number?, string?, string?]
    >,
    packRows: UgcAnalysis["packAlignment"],
    markers: UgcAnalysis["markers"],
    transcript: UgcAnalysis["transcript"],
    scenes: UgcAnalysis["scenes"],
    onScreen: UgcAnalysis["onScreenText"],
    opts?: { failed?: boolean; failureReason?: string; confidence?: "Low" | "Medium" | "High" },
): UgcAnalysis => ({
    assetId,
    createdAt: hoursAgo(6),
    score,
    confidence: opts?.confidence ?? (score >= 80 ? "High" : score >= 60 ? "Medium" : "Low"),
    summary,
    reason,
    nextAction,
    dimensions: dims.map(([id, s, r, ts, req, action]) => ({
        id,
        label: dimensionLabel(id),
        score: s,
        reason: r,
        timestampSec: ts,
        requirement: req,
        action,
    })),
    packAlignment: packRows,
    markers,
    transcript,
    scenes,
    onScreenText: onScreen,
    failed: opts?.failed,
    failureReason: opts?.failureReason,
});

function dimensionLabel(id: UgcAnalysis["dimensions"][number]["id"]): string {
    return {
        hook: "Hook Strength",
        "product-visibility": "Product Visibility",
        "demo-clarity": "Demo Clarity",
        authenticity: "Creator Authenticity",
        "problem-solution": "Problem–Solution Fit",
        "offer-clarity": "Offer Clarity",
        cta: "CTA Strength",
        "pack-alignment": "Campaign Pack Alignment",
        "shop-readiness": "TikTok Shop Readiness",
        compliance: "Compliance Safety",
    }[id];
}

