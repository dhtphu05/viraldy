// ------------- Derived campaign summaries -------------
function campaignSummary(
    campaignId: string,
    name: string,
    product: string,
    status: CampaignPerfSummary["status"],
    primary: CampaignPerfSummary["primaryDecision"],
    dq: CampaignPerfSummary["dataQuality"],
): CampaignPerfSummary {
    const assets = seedPerfAssets.filter((a) => a.campaignId === campaignId);
    const sum = (fn: (a: PerfAsset) => number) => assets.reduce((n, a) => n + fn(a), 0);
    const gmv = sum((a) => a.gmv);
    const grossProfit = sum(
        (a) => a.gmv - a.commission - a.cogs - a.adSpend - a.refunds - a.sampleCost,
    );
    const sampleCost = sum((a) => a.sampleCost);
    const adSpend = sum((a) => a.adSpend);
    const orders = sum((a) => a.orders);
    const clicks = sum((a) => a.productClicks);
    const views = sum((a) => a.views);
    const refunds = sum((a) => a.refunds);
    return {
        campaignId,
        campaignName: name,
        product,
        status,
        activeAssets: assets.length,
        gmv,
        grossProfit: Math.round(grossProfit),
        sampleEfficiency: sampleCost > 0 ? Number((gmv / sampleCost).toFixed(1)) : 0,
        adSpend,
        roas: adSpend > 0 ? Number((gmv / adSpend).toFixed(2)) : null,
        orders,
        productClicks: clicks,
        ctr: views > 0 ? clicks / views : 0,
        watchRate: assets.length > 0 ? sum((a) => a.watchRate) / assets.length : 0,
        refundRate: gmv > 0 ? refunds / gmv : 0,
        rightsReady: assets.filter((a) => a.rightsStatus === "complete").length,
        avgUgcScore: assets.length > 0 ? Math.round(sum((a) => a.ugcScore) / assets.length) : 0,
        dataQuality: dq,
        primaryDecision: primary,
        lastUpdated: demoDaysAgo(0.3),
    };
}

