// ------------- Trend points (30 days per campaign) -------------
function makeTrend(
    campaignId: string,
    base: { gmv: number; orders: number; ctr: number; watch: number },
): TrendPoint[] {
    const out: TrendPoint[] = [];
    const seed = campaignId.charCodeAt(campaignId.length - 1);
    for (let i = 29; i >= 0; i--) {
        const noise = Math.sin((i + seed) * 0.7) * 0.18 + Math.cos(i * 0.3) * 0.08;
        const trend = 1 + (29 - i) * 0.01;
        const gmv = Math.max(0, Math.round(base.gmv * (1 + noise) * trend));
        const orders = Math.max(0, Math.round(base.orders * (1 + noise) * trend));
        const clicks = Math.max(0, Math.round(orders * (12 + Math.abs(noise) * 6)));
        const ctr = Math.max(0.002, base.ctr * (1 + noise * 0.4));
        const watch = Math.min(0.9, Math.max(0.2, base.watch * (1 + noise * 0.2)));
        const gp = Math.round(gmv * 0.32);
        out.push({
            date: demoDaysAgo(i),
            gmv,
            grossProfit: gp,
            orders,
            productClicks: clicks,
            ctr: Number(ctr.toFixed(4)),
            watchRate: Number(watch.toFixed(3)),
            sampleEfficiency: Number((gmv / Math.max(1, base.orders * 2)).toFixed(1)),
        });
    }
    return out;
}

